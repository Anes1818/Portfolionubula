/* Lossless web delivery of supplied cutouts. No retouching or generated artwork. */
const fs=require('node:fs'),path=require('node:path'),sharp=require('sharp');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'assets/halloween');
const sources={'rose-black-a':'234823_755','rose-black-b':'234824_130','black-bow-tails':'234823_567','pink-dark-daisy':'234823_903','blue-thistle':'234824_174','black-fan-wrap':'234824_381','scream-mask':'234824_467'};
(async()=>{
 const embedded={},report=[];
 for(const [name,stamp] of Object.entries(sources)){
  const input=path.join(dir,name+'.png'),output=path.join(dir,name+'.webp');
  if(!fs.existsSync(input))fs.copyFileSync(path.join('C:/Users/laptops zone/Downloads/Telegram Desktop','IMG_20261005_'+stamp+'.png'),input);
  await sharp(input).webp({lossless:true,effort:6}).toFile(output);
  const a=await sharp(input).ensureAlpha().raw().toBuffer(),b=await sharp(output).ensureAlpha().raw().toBuffer(),m=await sharp(output).metadata();
  if(!m.hasAlpha||a.length!==b.length)throw Error('Invalid artwork '+name);
  let transparent=0;
  for(let i=0;i<a.length;i+=4){if(a[i+3]!==b[i+3]||a[i+3]&&[0,1,2].some(c=>a[i+c]!==b[i+c]))throw Error('Pixel mismatch '+name);if(!a[i+3])transparent++;}
  if(!transparent)throw Error('Missing alpha '+name);
  embedded['assets/halloween/'+name+'.webp']='data:image/webp;base64,'+fs.readFileSync(output).toString('base64');
  report.push({name,source:'IMG_20261005_'+stamp+'.png',width:m.width,height:m.height,transparentPixels:transparent,visiblePixelsAndAlphaExact:true});
 }
 embedded['assets/halloween/ghost-decal.svg']='data:image/svg+xml;base64,'+fs.readFileSync(path.join(dir,'ghost-decal.svg')).toString('base64');
 fs.writeFileSync(path.join(root,'halloween-embedded.js'),'/* Generated by tools/prepare-halloween.cjs */\nObject.assign(window.NEBULA_EMBED,'+JSON.stringify(embedded)+');\n');
 fs.writeFileSync(path.join(dir,'manifest.json'),JSON.stringify(report,null,2));console.log(report);
})().catch(e=>{console.error(e);process.exit(1)});
